export function normalizeSearch(value) {
  return value.normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/đ/g, 'd').replace(/Đ/g, 'D').toLowerCase().trim();
}

export function matchesService(service, category, query) {
  const text = [service.title, service.description, ...service.checks].join(' ');
  return (category === 'all' || service.category === category) && normalizeSearch(text).includes(normalizeSearch(query));
}
