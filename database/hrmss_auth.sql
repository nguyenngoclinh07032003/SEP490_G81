CREATE FUNCTION hrmss_set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW IS DISTINCT FROM OLD AND NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN
    NEW.updated_at := statement_timestamp() AT TIME ZONE 'UTC';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER trg_role_updated_at BEFORE UPDATE ON role
FOR EACH ROW EXECUTE FUNCTION hrmss_set_updated_at();
CREATE TRIGGER trg_user_account_updated_at BEFORE UPDATE ON user_account
FOR EACH ROW EXECUTE FUNCTION hrmss_set_updated_at();
CREATE TRIGGER trg_user_information_updated_at BEFORE UPDATE ON user_information
FOR EACH ROW EXECUTE FUNCTION hrmss_set_updated_at();
CREATE TRIGGER trg_user_location_state_updated_at BEFORE UPDATE ON user_location_state
FOR EACH ROW EXECUTE FUNCTION hrmss_set_updated_at();
CREATE TRIGGER trg_permission_updated_at BEFORE UPDATE ON permission
FOR EACH ROW EXECUTE FUNCTION hrmss_set_updated_at();
CREATE TRIGGER trg_role_permission_updated_at BEFORE UPDATE ON role_permission
FOR EACH ROW EXECUTE FUNCTION hrmss_set_updated_at();
