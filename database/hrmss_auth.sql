-- Revised baseline: choose FULL or USER-ONLY in separate empty databases.
-- Both scripts use schema hrmss and share the same six User/auth tables.
-- Do not run both scripts consecutively in the same database.
-- Sessions/refresh tokens, rotation/revocation and TTL live in Redis, not PostgreSQL.
-- Backend: normalize username/email with trim+lower before writes AND login lookup.
-- Username cannot contain @, so username/email login identifiers cannot collide.
-- Signup must assign CUSTOMER server-side; never accept role/status/permissions from public input.
-- Hash passwords in the backend; never return password_hash in API payloads.
-- Signup creates user_account + user_information atomically; location row is optional/lazy.
-- A role grant never replaces record ownership/assignment checks.
-- Account lock/role/grant changes must invalidate Redis sessions/caches as appropriate.
-- Permission catalog is a starter for auth and current business rules, not a full CRUD specification.

-- USER-ONLY baseline: 6 tables. No HRM business tables required.
BEGIN;
SET LOCAL TIME ZONE 'UTC';
CREATE SCHEMA IF NOT EXISTS hrmss;
SET LOCAL search_path = hrmss;

CREATE TABLE role (
  role_id BIGINT CHECK (role_id >= 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  role_code VARCHAR(40) NOT NULL,
  role_name VARCHAR(100) NOT NULL,
  description TEXT NULL,
  created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT (statement_timestamp() AT TIME ZONE 'UTC'),
  updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT (statement_timestamp() AT TIME ZONE 'UTC'),
  PRIMARY KEY (role_id),
  UNIQUE (role_code)
);

CREATE TABLE user_account (
  user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (user_id >= 0),
  role_id BIGINT NOT NULL CHECK (role_id >= 0),
  username VARCHAR(100) NOT NULL,
  email VARCHAR(254) NULL,
  password_hash VARCHAR(255) NOT NULL CHECK (length(btrim(password_hash)) > 0),
  account_status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE'
    CHECK (account_status IN ('ACTIVE', 'INACTIVE', 'LOCKED')),
  created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT (statement_timestamp() AT TIME ZONE 'UTC'),
  updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT (statement_timestamp() AT TIME ZONE 'UTC'),
  CONSTRAINT chk_username_canonical CHECK (username = lower(btrim(username)) AND length(username) > 0 AND position('@' in username) = 0),
  CONSTRAINT chk_email_canonical CHECK (email IS NULL OR (email = lower(btrim(email)) AND email ~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$')),
  CONSTRAINT uq_user_account_username UNIQUE (username),
  CONSTRAINT uq_user_account_email UNIQUE (email)
);

-- Create account and profile together in one backend transaction.
CREATE TABLE user_information (
  user_id BIGINT PRIMARY KEY REFERENCES user_account(user_id) ON DELETE CASCADE,
  full_name VARCHAR(200) NOT NULL CHECK (length(btrim(full_name)) > 0),
  phone VARCHAR(30) NULL,
  ava_storage_reference VARCHAR(255) NULL,
  created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT (statement_timestamp() AT TIME ZONE 'UTC'),
  updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT (statement_timestamp() AT TIME ZONE 'UTC')
);

-- Latest position only; this is not login/session storage or location history.
CREATE TABLE user_location_state (
  user_id BIGINT PRIMARY KEY REFERENCES user_account(user_id) ON DELETE CASCADE,
  location_sharing_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  latitude DECIMAL(10,7) NULL,
  longitude DECIMAL(10,7) NULL,
  location_accuracy DECIMAL(10,2) NULL CHECK (location_accuracy >= 0),
  location_recorded_at TIMESTAMP(6) WITHOUT TIME ZONE NULL,
  location_received_at TIMESTAMP(6) WITHOUT TIME ZONE NULL,
  location_session_expires_at TIMESTAMP(6) WITHOUT TIME ZONE NULL,
  location_state_version BIGINT NOT NULL DEFAULT 0 CHECK (location_state_version >= 0),
  created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT (statement_timestamp() AT TIME ZONE 'UTC'),
  updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT (statement_timestamp() AT TIME ZONE 'UTC'),
  CONSTRAINT chk_user_location_coordinates CHECK (
    (latitude IS NULL AND longitude IS NULL) OR
    (latitude IS NOT NULL AND longitude IS NOT NULL AND latitude BETWEEN -90 AND 90 AND longitude BETWEEN -180 AND 180)),
  CONSTRAINT chk_user_location_timestamps CHECK (
    latitude IS NULL OR (location_recorded_at IS NOT NULL AND location_received_at IS NOT NULL AND location_session_expires_at IS NOT NULL)),
  CONSTRAINT chk_user_location_disabled CHECK (
    location_sharing_enabled OR (latitude IS NULL AND longitude IS NULL AND location_accuracy IS NULL
      AND location_recorded_at IS NULL AND location_received_at IS NULL AND location_session_expires_at IS NULL))
);

CREATE TABLE permission (
  permission_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (permission_id >= 0),
  permission_code VARCHAR(100) NOT NULL UNIQUE,
  description TEXT NOT NULL,
  created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT (statement_timestamp() AT TIME ZONE 'UTC'),
  updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT (statement_timestamp() AT TIME ZONE 'UTC')
);

CREATE TABLE role_permission (
  role_id BIGINT NOT NULL REFERENCES role(role_id) ON DELETE CASCADE,
  permission_id BIGINT NOT NULL REFERENCES permission(permission_id) ON DELETE CASCADE,
  created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT (statement_timestamp() AT TIME ZONE 'UTC'),
  updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT (statement_timestamp() AT TIME ZONE 'UTC'),
  PRIMARY KEY (role_id, permission_id)
);
CREATE INDEX idx_role_permission_permission ON role_permission(permission_id);

