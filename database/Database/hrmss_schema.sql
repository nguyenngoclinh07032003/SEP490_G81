  assignment_id BIGINT CHECK (assignment_id >= 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  assigned_by BIGINT CHECK (assigned_by >= 0) NOT NULL,
  technician_id BIGINT CHECK (technician_id >= 0) NOT NULL,
  visit_id BIGINT CHECK (visit_id >= 0) NOT NULL,
  assigned_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  ended_at TIMESTAMP(6) WITHOUT TIME ZONE NULL,
  assignment_status VARCHAR(40) NOT NULL,
  planned_start TIMESTAMP(6) WITHOUT TIME ZONE NULL,
  planned_end TIMESTAMP(6) WITHOUT TIME ZONE NULL,
  started_at TIMESTAMP(6) WITHOUT TIME ZONE NULL,
  completed_at TIMESTAMP(6) WITHOUT TIME ZONE NULL,
  completion_note TEXT NULL,
  active_technician_id BIGINT CHECK (active_technician_id >= 0) GENERATED ALWAYS AS
    (CASE WHEN ended_at IS NULL AND completed_at IS NULL THEN technician_id ELSE NULL END) STORED,
  notes TEXT NULL,
  created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT (statement_timestamp() AT TIME ZONE 'UTC'),
  updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT (statement_timestamp() AT TIME ZONE 'UTC'),
  PRIMARY KEY (assignment_id),
  CHECK (ended_at IS NULL OR ended_at >= assigned_at),
  CONSTRAINT uq_assignment_visit_identity UNIQUE (visit_id, assignment_id),
  CONSTRAINT uq_assignment_active_pair UNIQUE (visit_id, active_technician_id),
  CONSTRAINT chk_assignment_plan CHECK (
    (planned_start IS NULL AND planned_end IS NULL) OR
    (planned_start IS NOT NULL AND planned_end IS NOT NULL AND planned_end > planned_start)
  ),
  CONSTRAINT chk_assignment_started CHECK (started_at IS NULL OR started_at >= assigned_at),
  CONSTRAINT chk_assignment_completed CHECK (
    completed_at IS NULL OR (completed_at >= assigned_at AND (started_at IS NULL OR completed_at >= started_at))
  ),
  CONSTRAINT chk_assignment_ended_completion CHECK (
    ended_at IS NULL OR completed_at IS NULL OR ended_at >= completed_at
  )
);

